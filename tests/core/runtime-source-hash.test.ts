import "@/core/config/load-env";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, utimesSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { afterAll, beforeEach, describe, expect, it } from "vitest";

/**
 * The runtime's build-detection hash, tested without a database or a build.
 *
 * A system that manages a Prisma schema has its client *generated into its own
 * source tree* (`output = "../src/generated/prisma"`), and `ensureBuilt` runs
 * `prisma generate` before every build. If that output is part of the hash, the
 * hash can never match the stored one: every cold boot rebuilds the system from
 * scratch. That is the difference between an app that opens in a second and one
 * that takes half a minute, so it is pinned here.
 */

const sandbox = mkdtempSync(join(tmpdir(), "runtime-hash-test-"));

const { hashRuntimeSources } = await import("@/core/systems/runtime/supervisor");

/** A system folder shaped like `system/grocery`: a Prisma schema with a generated client. */
function writeSystem(dir: string, opts: { generatorOutput?: string | null } = {}): string {
  mkdirSync(join(dir, "src", "features"), { recursive: true });
  mkdirSync(join(dir, "prisma"), { recursive: true });
  writeFileSync(join(dir, "package.json"), JSON.stringify({ name: "grocery" }));
  writeFileSync(join(dir, "src", "features", "sales.ts"), "export const sales = 1;\n");

  const output = opts.generatorOutput === undefined ? "../src/generated/prisma" : opts.generatorOutput;
  const generator =
    output === null
      ? 'generator client {\n  provider = "prisma-client"\n}\n'
      : `generator client {\n  provider = "prisma-client"\n  output   = "${output}"\n}\n`;
  writeFileSync(
    join(dir, "prisma", "schema.prisma"),
    `${generator}\ndatasource db {\n  provider = "postgresql"\n}\n`,
  );
  return dir;
}

/** Simulates `prisma generate`: rewrites the client with identical bytes, new mtimes. */
function regenerateClient(dir: string, outDir: string, mtimeSeconds: number): void {
  const target = join(dir, outDir);
  mkdirSync(join(target, "internal"), { recursive: true });
  const files = [
    join(target, "client.ts"),
    join(target, "models.ts"),
    join(target, "enums.ts"),
    join(target, "internal", "class.ts"),
  ];
  for (const file of files) {
    writeFileSync(file, "// generated by prisma generate\nexport const generated = true;\n");
    const when = mtimeSeconds / 1000;
    utimesSync(file, when, when);
  }
}

beforeEach(() => {
  rmSync(sandbox, { recursive: true, force: true });
  mkdirSync(sandbox, { recursive: true });
});

afterAll(() => {
  rmSync(sandbox, { recursive: true, force: true });
});

describe("runtime source hash", () => {
  it("is stable when only the generated Prisma client is rewritten", () => {
    const dir = writeSystem(join(sandbox, "grocery"));
    regenerateClient(dir, "src/generated/prisma", 1_700_000_000_000);
    const first = hashRuntimeSources(dir);

    // Same bytes, different mtimes — exactly what `prisma generate` produces.
    regenerateClient(dir, "src/generated/prisma", 1_800_000_000_000);
    const second = hashRuntimeSources(dir);

    expect(second).toBe(first);
  });

  it("still detects a real source edit", () => {
    const dir = writeSystem(join(sandbox, "grocery"));
    regenerateClient(dir, "src/generated/prisma", 1_700_000_000_000);
    const before = hashRuntimeSources(dir);

    writeFileSync(join(dir, "src", "features", "sales.ts"), "export const sales = 2;\n");
    const when = 1_900_000_000 / 1000;
    utimesSync(join(dir, "src", "features", "sales.ts"), when, when);

    expect(hashRuntimeSources(dir)).not.toBe(before);
  });

  it("honours a generator output that is not under src/", () => {
    const dir = writeSystem(join(sandbox, "grocery"), { generatorOutput: "../generated-client" });
    regenerateClient(dir, "generated-client", 1_700_000_000_000);
    const first = hashRuntimeSources(dir);

    regenerateClient(dir, "generated-client", 1_800_000_000_000);
    expect(hashRuntimeSources(dir)).toBe(first);
  });

  it("ignores .next and node_modules, and the runtime state file", () => {
    const dir = writeSystem(join(sandbox, "grocery"));
    const before = hashRuntimeSources(dir);

    mkdirSync(join(dir, ".next", "server"), { recursive: true });
    writeFileSync(join(dir, ".next", "server", "chunk.js"), "junk");
    mkdirSync(join(dir, "node_modules", "left-pad"), { recursive: true });
    writeFileSync(join(dir, "node_modules", "left-pad", "index.js"), "module.exports = 1;");
    writeFileSync(join(dir, ".runtime.json"), JSON.stringify({ sourceHash: "stale" }));
    writeFileSync(join(dir, ".env.local"), "SECRET=1");

    expect(hashRuntimeSources(dir)).toBe(before);
  });

  it("survives a system with no Prisma schema at all", () => {
    const dir = join(sandbox, "plain");
    mkdirSync(join(dir, "src"), { recursive: true });
    writeFileSync(join(dir, "package.json"), JSON.stringify({ name: "plain" }));
    writeFileSync(join(dir, "src", "index.ts"), "export const ok = true;\n");

    expect(() => hashRuntimeSources(dir)).not.toThrow();
    expect(hashRuntimeSources(dir)).toBe(hashRuntimeSources(dir));
  });

  it("ignores the boot bootstrap, which never reaches the build output", () => {
    // `prisma/bootstrap.ts` is run by `tsx` against the org's own database and is
    // imported by nothing, so `next build` never sees it. Hashing it would make
    // one added reference row cost every org a full production rebuild.
    const dir = writeSystem(join(sandbox, "grocery"));
    const before = hashRuntimeSources(dir);

    writeFileSync(join(dir, "prisma", "bootstrap.ts"), "console.log('seeded');\n");
    const when = 1_900_000_000 / 1000;
    utimesSync(join(dir, "prisma", "bootstrap.ts"), when, when);

    expect(hashRuntimeSources(dir)).toBe(before);
  });

  it("still notices a change to the Prisma schema or the migrations", () => {
    // The bootstrap is exempt because it cannot affect a build. A migration or a
    // schema edit can — `prisma generate` and `migrate deploy` both re-run from
    // it — so the exemption must not reach them.
    const dir = writeSystem(join(sandbox, "grocery"));
    const before = hashRuntimeSources(dir);

    mkdirSync(join(dir, "prisma", "migrations", "20260101000000_init"), { recursive: true });
    writeFileSync(join(dir, "prisma", "migrations", "20260101000000_init", "migration.sql"), "SELECT 1;");

    expect(hashRuntimeSources(dir)).not.toBe(before);
  });

  it("reads the generator output from the org copy's own schema, not the master", () => {
    // The org copy is what gets hashed; if it declares a different output, that
    // is the directory that must be ignored.
    const dir = writeSystem(join(sandbox, "grocery"), { generatorOutput: null });
    mkdirSync(join(dir, "src", "generated", "prisma"), { recursive: true });
    writeFileSync(join(dir, "src", "generated", "prisma", "client.ts"), "v1");
    const when = 1_700_000_000 / 1000;
    utimesSync(join(dir, "src", "generated", "prisma", "client.ts"), when, when);
    const before = hashRuntimeSources(dir);

    writeFileSync(join(dir, "src", "generated", "prisma", "client.ts"), "v1");
    utimesSync(join(dir, "src", "generated", "prisma", "client.ts"), when * 2, when * 2);

    // No generator output declared => nothing is excluded => the rewrite shows up.
    expect(hashRuntimeSources(dir)).not.toBe(before);
    expect(readFileSync(join(dir, "prisma", "schema.prisma"), "utf8")).toContain("provider = \"prisma-client\"");
  });
});
